#Write a program that:
#Generates a random number between 1 and 100.
#Finds its square root using the math module.
#Python Programming FYMCA Semester 1 (2026-28 batch)
#Sample Output:
#Random Number: 64
#Square Root: 8.0
import math
import random
a=random.randint(1,100)
squarert=math.sqrt(a)
print(f"random no:{a}")
print(f"squareroot:{squarert}")
